/**
 * AI Cyber Wire — public editorial landing page.
 * SSR-rendered, ISR-cached for 10 minutes.
 *
 * Pulls today's AEGIS-triaged alerts from the DB and lays them out
 * broadsheet-style: masthead → big numbers → lead story → brief grid →
 * index → footer.
 *
 * Phase 9.6 narrowing: default query gates on
 * `(ai_relevance >= 0.5 OR severity = 'critical')`. The `?include=all`
 * query parameter restores the pre-Phase-9 broad-cyber view for archive
 * use, and that view is marked `noindex` so the canonical AI-niche
 * surface stays the indexed public face.
 */
export const revalidate = 600; // 10 minutes

interface PageProps {
  searchParams?: Promise<{ include?: string }>;
}

export async function generateMetadata({ searchParams }: PageProps): Promise<Metadata> {
  const params = (await searchParams) ?? {};
  const archive = params.include === 'all';
  return {
    title: archive ? 'AI Cyber Wire — Archive (broad cyber)' : 'AI Cyber Wire — Cocoa AI',
    description: archive
      ? 'Broad-cyber archive view of the AI Cyber Wire. The canonical AI-niche surface lives at /feed/cyber-wire without query parameters.'
      : 'AEGIS-triaged AI-cyber intelligence brief: prompt injection, LLM jailbreaks, agentic safety, AI-vendor incidents, autonomous offensive AI.',
    // Keep the archive view out of search indexes so the canonical narrow
    // surface stays the public face. Public RSS subscribers can still
    // request ?include=all via /feed/cyber-wire.rss?include=all directly.
    robots: archive ? { index: false, follow: false } : undefined,
  };
}

type AlertRow = {
  id: number;
  alert_type: string;
  entity_kind: string | null;
  entity_id: string | null;
  severity: string;
  headline: string;
  summary: string | null;
  published_at: string;
  status: string;
};

type MetricsRow = {
  ai_cves_24h: string;
  active_kev: string;
  breach_records: string;
  threat_actors: string;
};

export default async function CyberWirePage({ searchParams }: PageProps) {
  if (!isCapabilityEnabled('publicFeed')) notFound();
  const params = (await searchParams) ?? {};
  const includeAll = params.include === 'all';

  const [alerts, metrics] = await Promise.all([
    fetchAlerts(includeAll).catch(() => [] as AlertRow[]),
    fetchMetrics().catch(() => null),
  ]);

  const lead = alerts[0] ?? null;
  // Dedupe by headline since seed data has duplicates from re-apply
  const seenHeadlines = new Set<string>();
  if (lead) seenHeadlines.add(lead.headline);
  const remaining = alerts.slice(1).filter((a) => {
    if (seenHeadlines.has(a.headline)) return false;
    seenHeadlines.add(a.headline);
    return true;
  });
  const briefs = remaining.slice(0, 3);
  const indexEntries = alerts.filter(
    (a, i, arr) => arr.findIndex((x) => x.headline === a.headline) === i,
  );

  return (
    <main className={styles.page}>
      <div className={styles.container}>
        <Masthead volume={1} issue={editionNumber()} dateline={formatDateline(new Date())} />

        <BigNumbersStrip items={buildBigNumbers(metrics)} />

        {lead ? (
          <LeadStory
            kicker={buildKicker(lead)}
            headline={lead.headline}
            byline={`By ${AGENT_IDENTITY.name} · ${relativeTime(lead.published_at)}`}
            body={lead.summary ?? 'Awaiting analyst summary.'}
            entityKind={lead.entity_kind}
            entityId={lead.entity_id}
          />
        ) : (
          <div className={styles.empty}>{'// awaiting wire sync //'}</div>
        )}

        <BriefGrid briefs={briefs.map(toBrief)} />

        <IndexList entries={indexEntries.map(toIndexEntry)} />

        <footer className={styles.footer}>
          <div className={styles.footerLine}>
            Cocoa AI Threat Deck ·{' '}
            <a
              className={styles.footerLink}
              href="https://github.com/cocoa-labs/threat-deck"
              target="_blank"
              rel="noopener noreferrer"
            >
              cocoa-labs/hacking-monitor
            </a>
          </div>
          <div>Generated by AEGIS · Last sync: {relativeTime(lead?.published_at)}</div>
        </footer>
      </div>
    </main>
  );
}

/* ─── Data layer ─── */

async function fetchAlerts(includeAll: boolean): Promise<AlertRow[]> {
  // Phase 9.6 — canonical narrow query gates on AI-cyber relevance OR
  // critical severity (so a critical non-AI CVE still surfaces — see the
  // PRD §9.6 "general-cyber items stay visible when severity=critical"
  // contract). COALESCE handles legacy unscored rows.
  // Archive view (?include=all) restores the pre-Phase-9 broad-cyber
  // query and is marked noindex via generateMetadata above.
  const result = includeAll
    ? await query<AlertRow>(
        `SELECT id, alert_type, entity_kind, entity_id, severity, headline, summary,
                published_at::text, status
         FROM aegis_pipeline_alerts
         WHERE severity IN ('critical', 'high')
         ORDER BY published_at DESC NULLS LAST, id DESC
         LIMIT 24`,
      )
    : await query<AlertRow>(
        `SELECT id, alert_type, entity_kind, entity_id, severity, headline, summary,
                published_at::text, status
         FROM aegis_pipeline_alerts
         WHERE (COALESCE(ai_relevance, 0) >= 0.5 OR severity = 'critical')
         ORDER BY published_at DESC NULLS LAST, id DESC
         LIMIT 24`,
      );
  return result.rows;
}

async function fetchMetrics(): Promise<MetricsRow | null> {
  // Phase 9.6 BIG NUMBERS swap: "Critical CVEs (tracked)" tile becomes
  // "AI-stack CVEs (24h)" — counts CVE-typed pipeline alerts in the last
  // 24h that are AI-relevant OR critical. This is what subscribers want
  // to see on the public landing: 'how many AI-cyber items hit today?'
  const result = await query<MetricsRow>(
    `SELECT
       (SELECT COUNT(*) FROM aegis_pipeline_alerts
         WHERE entity_kind = 'cve'
           AND published_at::timestamptz >= NOW() - INTERVAL '24 hours'
           AND (COALESCE(ai_relevance, 0) >= 0.5 OR severity = 'critical')
       )::text AS ai_cves_24h,
       (SELECT COUNT(*) FROM aegis_kev)::text AS active_kev,
       (SELECT COALESCE(SUM(records_compromised), 0) FROM aegis_incidents)::text AS breach_records,
       (SELECT COUNT(*) FROM aegis_threat_actors)::text AS threat_actors`,
  );
  return result.rows[0] ?? null;
}

/* ─── Mappers ─── */

function toBrief(a: AlertRow): Brief {
  return {
    id: a.id,
    kicker: buildKicker(a),
    headline: a.headline,
    summary: a.summary ?? '',
    readMoreHref: buildReadMoreUrl(a.entity_kind, a.entity_id),
  };
}

function toIndexEntry(a: AlertRow): IndexEntry {
  return {
    id: a.id,
    time: formatShortTime(a.published_at),
    tag: alertTypeToTag(a.alert_type),
    headline: a.headline,
    href: buildReadMoreUrl(a.entity_kind, a.entity_id),
  };
}

function buildKicker(a: AlertRow): string {
  const ago = relativeTime(a.published_at);
  return `${a.severity.toUpperCase()} · ${alertTypeToTag(a.alert_type)} · ${ago}`;
}

function alertTypeToTag(alertType: string): IndexEntry['tag'] {
  if (alertType.includes('kev')) return 'KEV';
  if (alertType.includes('breach')) return 'BRH';
  if (alertType.includes('patch')) return 'PCH';
  return 'CVE';
}

function buildReadMoreUrl(kind: string | null, id: string | null): string | null {
  if (!kind || !id) return null;
  if (kind === 'cve') return `/api/aegis/cves/view?id=${encodeURIComponent(id)}`;
  if (kind === 'incident') return `/api/aegis/incidents/view?id=${encodeURIComponent(id)}`;
  if (kind === 'kev') return `/api/aegis/kev/view?id=${encodeURIComponent(id)}`;
  return null;
}

/* ─── Big numbers shaping ─── */

function buildBigNumbers(m: MetricsRow | null): BigNumber[] {
  return [
    { label: 'AI-stack CVEs', value: formatInt(m?.ai_cves_24h), unit: '24h' },
    { label: 'KEV entries', value: formatInt(m?.active_kev), unit: 'active' },
    {
      label: 'Breach records',
      value: formatLargeInt(m?.breach_records),
      unit: 'compromised',
    },
    { label: 'Threat actors', value: formatInt(m?.threat_actors), unit: 'monitored' },
  ];
}

function formatInt(s: string | undefined): string {
  if (!s) return '0';
  const n = Number(s);
  if (Number.isNaN(n)) return '0';
  return n.toString().padStart(2, '0');
}

function formatLargeInt(s: string | undefined): string {
  if (!s) return '0';
  const n = Number(s);
  if (Number.isNaN(n) || n === 0) return '0';
  if (n >= 1_000_000_000) return `${(n / 1_000_000_000).toFixed(1)}B`;
  if (n >= 1_000_000) return `${Math.round(n / 1_000_000)}M`;
  if (n >= 1_000) return `${Math.round(n / 1_000)}K`;
  return n.toString();
}

/* ─── Date helpers ─── */

function formatDateline(d: Date): string {
  const day = d.toLocaleDateString('en-US', {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    year: 'numeric',
    timeZone: 'America/New_York',
  });
  const time = d.toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
    timeZone: 'America/New_York',
  });
  return `${day} · ${time} ET`;
}

function formatShortTime(iso: string | undefined): string {
  if (!iso) return '—';
  try {
    const d = new Date(iso);
    if (Number.isNaN(d.getTime())) return '—';
    return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
  } catch {
    return '—';
  }
}

function relativeTime(iso: string | undefined): string {
  if (!iso) return 'recently';
  const t = Date.parse(iso);
  if (Number.isNaN(t)) return 'recently';
  const diffMin = Math.round((Date.now() - t) / 60_000);
  if (diffMin < 1) return 'just now';
  if (diffMin < 60) return `${diffMin}m ago`;
  const diffH = Math.round(diffMin / 60);
  if (diffH < 24) return `${diffH}h ago`;
  const diffD = Math.round(diffH / 24);
  if (diffD < 30) return `${diffD}d ago`;
  const diffMo = Math.round(diffD / 30);
  if (diffMo < 12) return `${diffMo}mo ago`;
  return `${Math.round(diffMo / 12)}y ago`;
}

/** Day-of-year as a rotating "issue number" (Vol. 1, No. {1..365}). */
function editionNumber(): number {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  return Math.floor(diff / (1000 * 60 * 60 * 24));
}
