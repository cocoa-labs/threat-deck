-- ═══════════════════════════════════════════════
-- AEGIS OUTBOUND DRAFTS — Pre-publish staging
-- ═══════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS aegis_outbound_drafts (
  id                BIGSERIAL PRIMARY KEY,
  source_alert_id   INTEGER,                                    -- soft link: aegis_pipeline_alerts.id (no FK; drafts can outlive alerts)
  channel           TEXT NOT NULL,                              -- 'twitter' | 'email' | 'rss'
  draft_type        TEXT NOT NULL,                              -- 'daily_brief' | 'breaking' | 'weekly_deepdive' | 'patch_thread' | 'predictions_thread'
  agent_mode        TEXT NOT NULL,                              -- 'anchor' | 'analyst' | 'fix_architect'
  headline          TEXT NOT NULL,                              -- single-line summary for queue row
  preview_text      TEXT,                                       -- first ~140 chars for queue preview
  draft_payload     JSONB NOT NULL,                             -- channel-specific: tweets[], email body, RSS xml
  ai_relevance      NUMERIC(4,3),                               -- 0.000-1.000; nullable for non-scored drafts
  severity          TEXT,                                       -- 'critical' | 'high' | 'medium' | 'low' — copied from source alert for queue sort
  status            TEXT NOT NULL DEFAULT 'drafted',            -- drafted | edited | approved | rejected | published | superseded
  created_by        TEXT NOT NULL,                              -- 'agent' | 'cron:daily_brief' | 'cron:weekly_deepdive' | user email
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  decided_at        TIMESTAMPTZ,
  decided_by        TEXT,                                       -- approver email or 'auto'
  rejection_reason  TEXT,
  published_at      TIMESTAMPTZ,
  outbound_log_id   INTEGER REFERENCES aegis_outbound_log(id) ON DELETE SET NULL,
  CHECK (status IN ('drafted','edited','approved','rejected','published','superseded')),
  CHECK (channel IN ('twitter','email','rss')),
  CHECK (draft_type IN ('daily_brief','breaking','weekly_deepdive','patch_thread','predictions_thread')),
  CHECK (agent_mode IN ('anchor','analyst','fix_architect')),
  CHECK (severity IS NULL OR severity IN ('critical','high','medium','low','info')),
  CHECK (ai_relevance IS NULL OR (ai_relevance >= 0 AND ai_relevance <= 1))
);

COMMENT ON COLUMN aegis_outbound_drafts.draft_payload IS 'Channel-specific structure. twitter: {tweets:[{text,replyToTweetId?}],canonicalHashtag}. email: {template,subject,recipients,bodyJson}. rss: {title,body,publishedAt}.';
COMMENT ON COLUMN aegis_outbound_drafts.source_alert_id IS 'Soft link to aegis_pipeline_alerts.id. Deliberately not a FK so drafts can outlive alerts (alerts may be archived; the draft history must remain auditable).';

-- Hot indexes for the common queries:
--   "approval queue: what's pending?"       → (status, created_at)
--   "per-channel queue filter"              → (channel, status, created_at)
--   "stale-critical sweep for escalation"   → partial idx on pending+severity
--   "what drafts came from this alert?"     → (source_alert_id)
CREATE INDEX IF NOT EXISTS idx_drafts_status_created   ON aegis_outbound_drafts (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_drafts_channel_status   ON aegis_outbound_drafts (channel, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_drafts_pending_severity ON aegis_outbound_drafts (severity, created_at DESC)
  WHERE status IN ('drafted','edited');
CREATE INDEX IF NOT EXISTS idx_drafts_source_alert     ON aegis_outbound_drafts (source_alert_id);

-- ═══════════════════════════════════════════════
-- AEGIS NEWS ENRICHMENTS — AI-relevance scoring cache (durable)
-- ═══════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS aegis_news_enrichments (
  item_url      TEXT PRIMARY KEY,
  ai_relevance  NUMERIC(4,3) NOT NULL,                          -- 0.000-1.000
  ai_category   TEXT,                                           -- 'vendor_incident' | 'defensive' | 'offensive' | 'agentic_safety' | 'unrelated'
  model_used    TEXT,                                           -- 'keywords' | 'haiku-4-5'
  scored_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  evidence_json JSONB NOT NULL DEFAULT '{}'::jsonb,             -- matched terms, Haiku response, rationale
  CHECK (ai_relevance >= 0 AND ai_relevance <= 1),
  CHECK (ai_category IS NULL OR ai_category IN ('vendor_incident','defensive','offensive','agentic_safety','unrelated')),
  CHECK (model_used IS NULL OR model_used IN ('keywords','haiku-4-5'))
);

COMMENT ON COLUMN aegis_news_enrichments.evidence_json IS 'Why the scorer arrived at this score. For keywords: {matchedTerms:[],negative:[]}. For Haiku: {prompt,response,parsedAt}.';

CREATE INDEX IF NOT EXISTS idx_enrichments_relevance ON aegis_news_enrichments (ai_relevance DESC, scored_at DESC);
CREATE INDEX IF NOT EXISTS idx_enrichments_category  ON aegis_news_enrichments (ai_category, scored_at DESC);

-- ═══════════════════════════════════════════════
-- ALTER aegis_pipeline_alerts — store ai_relevance directly on the alert
-- ═══════════════════════════════════════════════
-- Pre-resolves the Phase 9.6 Cyber Wire narrowing join footgun. Storing
-- ai_relevance on the alert row lets the public RSS + editorial page filter
-- via `WHERE ai_relevance >= 0.5 OR severity = 'critical'` directly without
-- joining aegis_news_enrichments by URL (which we lack a stable link to).
-- Backfill: existing rows are left NULL; consumers should COALESCE(ai_relevance, 0).

ALTER TABLE aegis_pipeline_alerts ADD COLUMN IF NOT EXISTS ai_relevance NUMERIC(4,3);

ALTER TABLE aegis_pipeline_alerts
  ADD CONSTRAINT aegis_pipeline_alerts_ai_relevance_range
  CHECK (ai_relevance IS NULL OR (ai_relevance >= 0 AND ai_relevance <= 1));

CREATE INDEX IF NOT EXISTS idx_pipeline_alerts_ai_relevance ON aegis_pipeline_alerts (ai_relevance DESC NULLS LAST)
  WHERE ai_relevance IS NOT NULL;

-- ═══════════════════════════════════════════════
-- VIEW aegis_v_pending_drafts — Approval Queue UI source + escalation cron
-- ═══════════════════════════════════════════════
-- Sorts critical drafts to the top, computes age_seconds for the 2h-stale
-- escalation cron (9.5). The view is read by:
--   - GET /api/outbound/drafts?status=pending  (Approval Queue UI fetch)
--   - /api/outbound/escalate  cron sweep (every 30 min)

CREATE OR REPLACE VIEW aegis_v_pending_drafts AS
SELECT
  id,
  source_alert_id,
  channel,
  draft_type,
  agent_mode,
  headline,
  preview_text,
  ai_relevance,
  severity,
  status,
  created_by,
  created_at,
  EXTRACT(EPOCH FROM (NOW() - created_at))::int AS age_seconds
FROM aegis_outbound_drafts
WHERE status IN ('drafted','edited')
ORDER BY
  (severity = 'critical') DESC,
  (severity = 'high') DESC,
  ai_relevance DESC NULLS LAST,
  created_at DESC;
