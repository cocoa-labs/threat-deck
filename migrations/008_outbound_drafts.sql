-- Two new tables + one view + one ALTER, all serving the Phase 9 Twitter
-- AI-cyber engine + cross-channel Approval Queue.
--
-- 1. aegis_outbound_drafts
--    Holds the lifecycle of an outbound communication BEFORE it is published.
--    The agent (or a cron) stages a draft row with status='drafted'; a human
--    reviewer in the AgentDrawer Approval Queue then edits/approves/rejects.
--    On approval+publish, the dispatcher writes a row into aegis_outbound_log
--    (the existing post-send audit table) and back-links via outbound_log_id.
--
--    Lifecycle:        drafted -> edited(opt) -> approved -> published
--                                              \-> rejected
--                      drafted -> superseded   (when a newer draft replaces it)
--
--    aegis_outbound_log stays untouched. It remains the at-most-once post-send
--    audit log with UNIQUE(channel, entity_kind, entity_id, recipient).
--    This new table is the PRE-send staging surface; the two never overlap.
--
-- 2. aegis_news_enrichments
--    Per-item-URL cache for the AI-relevance scoring pipeline (Phase 9.2).
--    Persists what the scorer found (keyword score, Haiku tiebreak result,
--    final ai_relevance, ai_category) so subsequent passes hit the cache.
--    The Redis cache (TTL 7d) is the hot path; this is the durable record.
--
-- 3. aegis_v_pending_drafts (view)
--    Convenience read for the Approval Queue UI. Sorts critical drafts to
--    the top, computes age_seconds for the staleness escalation cron (9.5).
--
-- 4. ALTER aegis_pipeline_alerts ADD ai_relevance
--    Pre-resolves the Phase 9.6 Cyber Wire narrowing join footgun: with
--    ai_relevance stored DIRECTLY on the alert row, the public RSS + editorial
--    page can filter via `WHERE ai_relevance >= 0.5 OR severity = 'critical'`
--    without joining aegis_news_enrichments by URL (which would require an
--    extra schema link we don't have).
--
-- Single source of truth for enum literals: src/lib/outbound/constants.ts.
-- The CHECK constraints below MUST match those tuples exactly. If they
-- drift, inserts will fail with cryptic 'violates check constraint' errors.
-- See src/lib/outbound/constants.ts for the canonical list.
--
-- Do NOT edit this file after it has been applied to any environment.
