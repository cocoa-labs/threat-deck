-- Migration: verification_tokens
-- Created: 2026-05-23
--
-- Persistent magic-link verification token store. Replaces the in-process
-- Map<string,StoredToken> in src/lib/auth/adapter.ts that was wiped by
-- Next.js HMR on every auth-adjacent file edit — which made the dev sign-in
-- flow look perpetually broken (every fresh magic-link became unfindable as
-- soon as we touched any code).
--
-- Mirrors the Auth.js Adapter `VerificationToken` contract exactly:
--   { identifier, token, expires }
-- so the adapter rewrite can drop into createMagicLinkAdapter() without
-- changing the public signature.
--
-- Composite PK (identifier, token) matches Auth.js's exact lookup shape.
-- Used for atomic single-use DELETE ... RETURNING by the adapter.
--
-- Do NOT edit this file after it has been applied to any environment.

CREATE TABLE IF NOT EXISTS aegis_verification_tokens (
  identifier TEXT NOT NULL,                          -- the email address
  token      TEXT NOT NULL,                          -- hashed token (Auth.js hashes with NEXTAUTH_SECRET before calling)
  expires    TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (identifier, token)
);

-- Supports a periodic cleanup query (DELETE WHERE expires < NOW()) — not
-- used by the hot path. The hot path is DELETE ... WHERE PK=...; index unused.
CREATE INDEX IF NOT EXISTS idx_aegis_verif_expires ON aegis_verification_tokens (expires);

COMMENT ON TABLE aegis_verification_tokens IS 'Auth.js magic-link verification tokens. Single-use; deleted on consumption by the adapter. Rows that go unused expire on their own and can be reaped via DELETE WHERE expires < NOW().';
