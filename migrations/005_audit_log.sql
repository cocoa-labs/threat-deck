-- Append-only audit trail for security-sensitive operations:
--   - Authentication attempts (magic-link request, accept, allowlist rejection)
--   - Outbound writes (Twitter post, email digest send, RSS publish)
--   - Privileged mutations (alert rule create/edit, brief publish, escalation)
--   - Admin actions (manual KEV add, OAuth token rotation)
--
-- Read by: SECURITY runbook investigations, periodic compliance reports,
-- the agent itself when answering "what happened on the platform overnight?"
--
-- Designed as APPEND-ONLY:
--   - No UPDATE column; row is immutable once written.
--   - No FK references to other tables — audit rows must outlive whatever
--     they reference (deleted users, deleted alerts, etc.) without orphan errors.
--   - actor_id / target_id stored as TEXT, not FK, so we can record actions
--     against entities that have been deleted or never existed (e.g. failed
--     login attempt for an email that's not in users).
--
-- Sensitive payloads: details JSONB MUST NOT contain raw tokens, passwords,
-- API keys, or full email bodies. The audit layer (src/lib/audit.ts) is
-- responsible for redacting before insert; column comment enforces.
--
-- Do NOT edit this file after it has been applied to any environment.
-- For schema changes, write a NEW migration (NNN_<description>.sql).

-- ═══════════════════════════════════════════════
-- AEGIS AUDIT LOG — Security-sensitive event trail
-- ═══════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS aegis_audit_log (
  id            BIGSERIAL PRIMARY KEY,
  occurred_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  action        TEXT NOT NULL,                  -- canonical verb, e.g. 'auth.magic_link_requested'
  category      TEXT NOT NULL,                  -- 'auth' | 'outbound' | 'admin' | 'agent' | 'data'
  outcome       TEXT NOT NULL,                  -- 'success' | 'failure' | 'denied' | 'rate_limited'
  actor_id      TEXT,                           -- email/userId/'system'/'cron'; nullable for pre-auth events
  actor_ip      INET,                           -- client IP, if known
  actor_ua      TEXT,                           -- user-agent (truncated to 256 chars before insert)
  target_kind   TEXT,                           -- 'user' | 'alert_rule' | 'brief' | 'tweet' | 'email_digest'
  target_id     TEXT,                           -- string identifier (intentionally not FK)
  request_id    TEXT,                           -- correlation id from logger.child({requestId})
  details       JSONB NOT NULL DEFAULT '{}'::jsonb,  -- structured event payload (NEVER raw secrets)
  error_message TEXT                            -- present iff outcome != 'success'
);

-- Single-literal COMMENT (no || concat — pg's simple-query protocol rejects
-- string concatenation inside COMMENT ON ... IS when multiple statements are
-- batched, even though it's standard SQL elsewhere).
COMMENT ON COLUMN aegis_audit_log.details IS 'Structured event payload. MUST NOT contain raw secrets (passwords, tokens, API keys, full email bodies). The src/lib/audit.ts helper redacts before insert.';

-- Hot indexes for the common queries:
--   "what did $actor do recently?"  →  (actor_id, occurred_at)
--   "what happened to $target?"     →  (target_kind, target_id, occurred_at)
--   "all failures in last 24h"      →  (outcome, occurred_at)
--   "audit feed for the agent"      →  (occurred_at DESC)
CREATE INDEX IF NOT EXISTS idx_audit_actor      ON aegis_audit_log (actor_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_target     ON aegis_audit_log (target_kind, target_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_outcome    ON aegis_audit_log (outcome, occurred_at DESC) WHERE outcome != 'success';
CREATE INDEX IF NOT EXISTS idx_audit_occurred   ON aegis_audit_log (occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_action     ON aegis_audit_log (action, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_category   ON aegis_audit_log (category, occurred_at DESC);

-- Convenience view: recent failures across all categories (used by SECURITY runbook).
CREATE OR REPLACE VIEW aegis_v_audit_failures AS
SELECT
  id,
  occurred_at,
  action,
  category,
  outcome,
  actor_id,
  actor_ip::text AS actor_ip,
  target_kind,
  target_id,
  request_id,
  error_message
FROM aegis_audit_log
WHERE outcome IN ('failure', 'denied', 'rate_limited')
ORDER BY occurred_at DESC
LIMIT 1000;

-- Convenience view: per-actor recent activity (used for "what did this user do today?").
CREATE OR REPLACE VIEW aegis_v_audit_by_actor AS
SELECT
  actor_id,
  COUNT(*) AS total_events,
  COUNT(*) FILTER (WHERE outcome = 'success')      AS successes,
  COUNT(*) FILTER (WHERE outcome = 'failure')      AS failures,
  COUNT(*) FILTER (WHERE outcome = 'denied')       AS denied,
  COUNT(*) FILTER (WHERE outcome = 'rate_limited') AS rate_limited,
  MIN(occurred_at) AS first_event,
  MAX(occurred_at) AS last_event
FROM aegis_audit_log
WHERE actor_id IS NOT NULL
  AND occurred_at >= NOW() - INTERVAL '7 days'
GROUP BY actor_id
ORDER BY total_events DESC;
