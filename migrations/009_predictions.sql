-- Migration: predictions
-- Created: 2026-05-25
-- Phase: 11.0 (PRD-NextLevel-v1.md §11; plan-file 11.A)
--
-- Schema for the Phase 11 predictive analytics stack. Five model families
-- produce forecasts that this migration provisions storage for:
--
--   1. Logistic regression       → aegis_cve_forecasts
--   2. Bayesian Dirichlet-Cat    → aegis_actor_target_forecasts
--   3. Hidden Markov Model       → aegis_cve_lifecycle_states
--   4. State-space Kalman        → aegis_daily_metrics + aegis_timeseries_forecasts
--   5. Causal DAG (do-calculus)  → aegis_causal_edges + aegis_causal_counterfactuals
--
-- Plus a polymorphic outcome-tracking table (aegis_forecast_outcomes) that
-- feeds the per-model calibration on /feed/cyber-wire/predictions-accuracy,
-- and three convenience views that the panel + Header chips read directly.
--
-- Versioning: every forecast row carries a `model_version` string. This
-- lets us ship v0.1 of each model and then retrain to v0.2 without
-- invalidating historical forecasts — the calibration page can compare
-- versions and we can deprecate old ones at our leisure.
--
-- The `forecast_id` column in aegis_forecast_outcomes is intentionally
-- polymorphic (BIGINT + a `forecast_kind` discriminator) — same pattern as
-- aegis_outbound_log.entity_id. Lets a single outcomes table cover all five
-- model families without N separate outcome tables to keep in sync.
--
-- All forecast probability columns are NUMERIC(5,4) (0.0000-1.0000 with
-- 4 decimal places). NUMERIC over DOUBLE PRECISION here because we compare
-- against thresholds in queries (`p_exploited_30d > 0.7`) and want exact
-- semantics for the calibration math.
--
-- Idempotent: CREATE TABLE IF NOT EXISTS + DEFAULT-bearing ADD COLUMN.
-- Do NOT edit this file after it has been applied to any environment.
-- For schema changes, write a NEW migration (NNN_<description>.sql).

-- ═══════════════════════════════════════════════
-- AEGIS CVE FORECASTS — Logistic-regression exploit-likelihood per CVE
-- ═══════════════════════════════════════════════
-- One row per (cve_id, forecast_date, model_version). The daily forecast
-- cron (11.16) writes a new row each day; the IntelCardForecast section
-- reads the latest row for an entity; the predictions-accuracy page joins
-- against aegis_forecast_outcomes to compute calibration.
--
-- features_json captures the exact feature values fed into the model at
-- forecast time. This is critical for reproducibility — if the calibration
-- looks bad we need to be able to inspect WHICH features drove a specific
-- row's prediction, not just the prediction.

CREATE TABLE IF NOT EXISTS aegis_cve_forecasts (
  id              BIGSERIAL PRIMARY KEY,
  cve_id          TEXT NOT NULL REFERENCES aegis_cves(cve_id) ON DELETE CASCADE,
  forecast_date   DATE NOT NULL,
  model_version   TEXT NOT NULL,                              -- 'exploit-logistic-v0_1' etc.
  p_exploited_30d NUMERIC(5,4) NOT NULL,
  p_exploited_60d NUMERIC(5,4) NOT NULL,
  p_exploited_90d NUMERIC(5,4) NOT NULL,
  ci_low          NUMERIC(5,4),
  ci_high         NUMERIC(5,4),
  features_json   JSONB NOT NULL DEFAULT '{}'::jsonb,         -- {cvssV3, epssPercentile, daysSincePublish, …}
  generated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(cve_id, forecast_date, model_version),
  CHECK (p_exploited_30d >= 0 AND p_exploited_30d <= 1),
  CHECK (p_exploited_60d >= 0 AND p_exploited_60d <= 1),
  CHECK (p_exploited_90d >= 0 AND p_exploited_90d <= 1),
  CHECK (p_exploited_30d <= p_exploited_60d),                  -- monotonic horizon clamp
  CHECK (p_exploited_60d <= p_exploited_90d),
  CHECK (ci_low IS NULL OR (ci_low >= 0 AND ci_low <= 1)),
  CHECK (ci_high IS NULL OR (ci_high >= 0 AND ci_high <= 1)),
  CHECK (ci_low IS NULL OR ci_high IS NULL OR ci_low <= ci_high)
);

COMMENT ON TABLE aegis_cve_forecasts IS 'Phase 11.B — logistic regression P(exploited in N days) per CVE per day. Read by IntelCardForecast (CVE kind), PredictionsPanel LOGISTIC view, and /feed/cyber-wire/predictions-accuracy.';

CREATE INDEX IF NOT EXISTS idx_cve_forecasts_date_p30 ON aegis_cve_forecasts (forecast_date DESC, p_exploited_30d DESC);
CREATE INDEX IF NOT EXISTS idx_cve_forecasts_cve_date ON aegis_cve_forecasts (cve_id, forecast_date DESC);
CREATE INDEX IF NOT EXISTS idx_cve_forecasts_model    ON aegis_cve_forecasts (model_version, forecast_date DESC);

-- ═══════════════════════════════════════════════
-- AEGIS ACTOR TARGET FORECASTS — Bayesian Dirichlet-Categorical
-- ═══════════════════════════════════════════════
-- One row per (actor_id, forecast_date, model_version). top_sectors_json
-- and top_countries_json store the top-5 posterior means + 95% credible
-- intervals; posterior_alpha_json caches the full Dirichlet posterior so
-- re-querying (different display thresholds, different counts) doesn't
-- re-run the inference. This is cheap because the posterior is a single
-- vector of α values; storing it costs ~200 bytes per actor per day.

CREATE TABLE IF NOT EXISTS aegis_actor_target_forecasts (
  id                  BIGSERIAL PRIMARY KEY,
  actor_id            TEXT NOT NULL REFERENCES aegis_threat_actors(actor_id) ON DELETE CASCADE,
  forecast_date       DATE NOT NULL,
  model_version       TEXT NOT NULL,                          -- 'actor-target-bayesian-v0_1'
  top_sectors_json    JSONB NOT NULL DEFAULT '[]'::jsonb,     -- [{sector, pMean, pLow, pHigh}, …] top 5
  top_countries_json  JSONB NOT NULL DEFAULT '[]'::jsonb,     -- same shape, top 5
  posterior_alpha_json JSONB NOT NULL DEFAULT '{}'::jsonb,    -- {sector: α_post, …} full posterior
  generated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(actor_id, forecast_date, model_version)
);

COMMENT ON TABLE aegis_actor_target_forecasts IS 'Phase 11.B — Bayesian Dirichlet-Categorical posterior over next-target sectors/countries per actor per day. Read by IntelCardForecast (threat_actor kind), PredictionsPanel BAYESIAN view.';

CREATE INDEX IF NOT EXISTS idx_actor_forecasts_actor_date ON aegis_actor_target_forecasts (actor_id, forecast_date DESC);
CREATE INDEX IF NOT EXISTS idx_actor_forecasts_date       ON aegis_actor_target_forecasts (forecast_date DESC);

-- ═══════════════════════════════════════════════
-- AEGIS CVE LIFECYCLE STATES — HMM state distribution per CVE
-- ═══════════════════════════════════════════════
-- 5-state HMM (Discovered / POC_Available / Weaponized / Mass_Exploitation /
-- Patched_Saturated). state_distribution_json is a length-5 array of
-- posterior probabilities (forward-backward result). viterbi_path_json is
-- the most-likely state sequence for the observation history (debug/audit
-- use, not normally rendered). expected_days_to_kev is computed via
-- first-passage time on the transition matrix and is the headline number
-- for IntelCardForecast on CVEs that haven't yet been KEV-added.

CREATE TABLE IF NOT EXISTS aegis_cve_lifecycle_states (
  id                    BIGSERIAL PRIMARY KEY,
  cve_id                TEXT NOT NULL REFERENCES aegis_cves(cve_id) ON DELETE CASCADE,
  observation_date      DATE NOT NULL,
  model_version         TEXT NOT NULL,                        -- 'cve-lifecycle-hmm-v0_1'
  state_distribution_json JSONB NOT NULL,                     -- [0.05, 0.10, 0.60, 0.20, 0.05] — 5 probs summing to 1
  viterbi_path_json     JSONB,                                -- [0, 0, 1, 2, 2] — length = observation count
  expected_days_to_kev  NUMERIC(8,2),                         -- NULL if already in Mass_Exploitation state
  generated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(cve_id, observation_date, model_version)
);

COMMENT ON TABLE aegis_cve_lifecycle_states IS 'Phase 11.C — HMM posterior state distribution over the 5 CVE lifecycle states (Discovered / POC / Weaponized / Mass_Exploitation / Patched_Saturated). Drives the stacked-bar visualization in IntelCardForecast (CVE kind).';

CREATE INDEX IF NOT EXISTS idx_lifecycle_cve_date ON aegis_cve_lifecycle_states (cve_id, observation_date DESC);
CREATE INDEX IF NOT EXISTS idx_lifecycle_date     ON aegis_cve_lifecycle_states (observation_date DESC);

-- ═══════════════════════════════════════════════
-- AEGIS DAILY METRICS — Pre-computed time-series aggregations
-- ═══════════════════════════════════════════════
-- One row per calendar date with COUNT-per-day for the 5 metrics the
-- Kalman filter operates on. Refreshed nightly by the aggregations cron
-- (11.4). Pre-computing means the panel's TIMESERIES view + the Kalman
-- training input both query a single indexed table instead of running
-- 5 GROUP BYs across aegis_kev / aegis_incidents / aegis_breach_disclosures
-- / aegis_advisories / aegis_geo_threat_events on every read.

CREATE TABLE IF NOT EXISTS aegis_daily_metrics (
  date         DATE PRIMARY KEY,
  kev_adds     INTEGER NOT NULL DEFAULT 0,
  incidents    INTEGER NOT NULL DEFAULT 0,
  breaches     INTEGER NOT NULL DEFAULT 0,
  advisories   INTEGER NOT NULL DEFAULT 0,
  geo_events   INTEGER NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (kev_adds   >= 0),
  CHECK (incidents  >= 0),
  CHECK (breaches   >= 0),
  CHECK (advisories >= 0),
  CHECK (geo_events >= 0)
);

COMMENT ON TABLE aegis_daily_metrics IS 'Phase 11.A — pre-computed daily aggregations for fast time-series queries. Refreshed by /api/aegis/forecast-aggregations cron at 03:00 UTC. Source of truth for Kalman filter training inputs.';

-- ═══════════════════════════════════════════════
-- AEGIS TIMESERIES FORECASTS — Kalman filter projections
-- ═══════════════════════════════════════════════
-- One row per (metric_name, forecast_date, horizon_days, model_version).
-- The daily forecast cron projects metrics 7/30/90 days forward; the
-- PredictionsPanel TIMESERIES view reads the most-recent forecast row per
-- metric to render sparklines with CI bands.

CREATE TABLE IF NOT EXISTS aegis_timeseries_forecasts (
  id            BIGSERIAL PRIMARY KEY,
  metric_name   TEXT NOT NULL,                                -- 'kev_adds' | 'incidents' | 'breaches' | 'advisories' | 'geo_events'
  forecast_date DATE NOT NULL,                                -- the date the forecast was MADE
  horizon_days  INTEGER NOT NULL,                             -- 7, 30, 90
  p_low         NUMERIC(8,2) NOT NULL,                        -- 95% CI lower bound on metric value
  p_mid         NUMERIC(8,2) NOT NULL,                        -- median projection
  p_high        NUMERIC(8,2) NOT NULL,                        -- 95% CI upper bound
  trend         TEXT,                                         -- 'rising' | 'flat' | 'falling' — for Header TREND chip
  model_version TEXT NOT NULL,                                -- 'timeseries-kalman-v0_1'
  generated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(metric_name, forecast_date, horizon_days, model_version),
  CHECK (metric_name IN ('kev_adds','incidents','breaches','advisories','geo_events')),
  CHECK (horizon_days IN (7, 30, 90)),
  CHECK (p_low <= p_mid AND p_mid <= p_high),
  CHECK (trend IS NULL OR trend IN ('rising','flat','falling'))
);

CREATE INDEX IF NOT EXISTS idx_ts_metric_date     ON aegis_timeseries_forecasts (metric_name, forecast_date DESC);
CREATE INDEX IF NOT EXISTS idx_ts_metric_horizon  ON aegis_timeseries_forecasts (metric_name, horizon_days, forecast_date DESC);

-- ═══════════════════════════════════════════════
-- AEGIS CAUSAL EDGES — Learned edges in the actor→TTP→CVE→victim DAG
-- ═══════════════════════════════════════════════
-- The DAG structure is HAND-BUILT in code (src/lib/aegis/forecasting/causal-dag.ts).
-- This table caches the CPT entries (one row per edge in the DAG) so the do-
-- calculus inference doesn't re-count from the source tables on every query.
-- Refreshed nightly by the forecast-aggregations cron.
--
-- source_kind/target_kind are intentionally polymorphic ('actor' | 'ttp' |
-- 'cve' | 'victim' | 'breach' | 'patch_lag_bucket') so a single edges table
-- covers the whole DAG.

CREATE TABLE IF NOT EXISTS aegis_causal_edges (
  id              BIGSERIAL PRIMARY KEY,
  source_kind     TEXT NOT NULL,
  source_id       TEXT NOT NULL,
  target_kind     TEXT NOT NULL,
  target_id       TEXT NOT NULL,
  edge_type       TEXT NOT NULL,                              -- 'uses' | 'targets' | 'leads_to' | 'discloses' | 'modulates'
  weight          NUMERIC(5,4) NOT NULL,                      -- P(target | source) — conditional probability
  evidence_count  INTEGER NOT NULL DEFAULT 0,                 -- N rows in source tables this edge was counted from
  model_version   TEXT NOT NULL,                              -- 'causal-dag-v0_1'
  last_updated    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(source_kind, source_id, target_kind, target_id, edge_type, model_version),
  CHECK (weight >= 0 AND weight <= 1),
  CHECK (evidence_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_causal_source ON aegis_causal_edges (source_kind, source_id, edge_type);
CREATE INDEX IF NOT EXISTS idx_causal_target ON aegis_causal_edges (target_kind, target_id, edge_type);

-- ═══════════════════════════════════════════════
-- AEGIS CAUSAL COUNTERFACTUALS — do-calculus result cache
-- ═══════════════════════════════════════════════
-- Computing a do(X=x) intervention requires re-running variable elimination
-- over the mutilated DAG. For common scenarios (the four patch-lag buckets
-- × top-20 actors × 3 target variables = 240 cells) we precompute + cache.
-- scenario_hash is a stable hash over (evidence, intervention, target) so
-- the same query returns the same cached row.

CREATE TABLE IF NOT EXISTS aegis_causal_counterfactuals (
  id             BIGSERIAL PRIMARY KEY,
  scenario_hash  TEXT NOT NULL,                               -- sha256(evidence + intervention + target).slice(0,16)
  scenario_json  JSONB NOT NULL,                              -- {evidence, intervention, target}
  baseline_p     NUMERIC(5,4) NOT NULL,
  intervention_p NUMERIC(5,4) NOT NULL,
  model_version  TEXT NOT NULL,
  generated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(scenario_hash, model_version),
  CHECK (baseline_p >= 0 AND baseline_p <= 1),
  CHECK (intervention_p >= 0 AND intervention_p <= 1)
);

CREATE INDEX IF NOT EXISTS idx_counterfactuals_generated ON aegis_causal_counterfactuals (generated_at DESC);

-- ═══════════════════════════════════════════════
-- AEGIS FORECAST OUTCOMES — Ground-truth backfill for calibration
-- ═══════════════════════════════════════════════
-- Polymorphic by (forecast_kind, forecast_id). The daily outcome-backfill
-- cron (11.16) walks forecasts >30 days old without an outcome row and
-- checks the ground truth:
--   - CVE logistic   → did the CVE actually enter KEV within 30/60/90d?
--   - HMM            → did the predicted state at time T match the observed event?
--   - actor target   → did the actor target a sector in the predicted top-5 within window?
--   - timeseries     → did the realized metric value fall within the 95% CI?
--   - causal         → counterfactuals are unfalsifiable; we record but never label was_correct
--
-- Brier score = (p - outcome)^2; log-loss is clamped to [1e-6, 1-1e-6] to
-- avoid -Infinity. evidence_json captures what we observed (e.g. KEV row id,
-- breach disclosure id) so we can audit the labeling later.

CREATE TABLE IF NOT EXISTS aegis_forecast_outcomes (
  id                 BIGSERIAL PRIMARY KEY,
  forecast_kind      TEXT NOT NULL,                           -- 'cve_logistic' | 'actor_target' | 'cve_lifecycle' | 'timeseries' | 'causal'
  forecast_id        BIGINT NOT NULL,                         -- FK by-discriminator into aegis_*_forecasts.id
  model_version      TEXT NOT NULL,
  outcome_observed_at TIMESTAMPTZ NOT NULL,
  was_correct        BOOLEAN,                                 -- NULL for causal counterfactuals (unfalsifiable)
  brier_score        NUMERIC(7,6),                            -- 0.000000-1.000000
  log_loss           NUMERIC(8,6),                            -- 0.000000-13.815510 (-ln(1e-6))
  evidence_json      JSONB NOT NULL DEFAULT '{}'::jsonb,      -- {observedEventId, observedSector, …}
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(forecast_kind, forecast_id, model_version, outcome_observed_at),
  CHECK (forecast_kind IN ('cve_logistic','actor_target','cve_lifecycle','timeseries','causal')),
  CHECK (brier_score IS NULL OR (brier_score >= 0 AND brier_score <= 1)),
  CHECK (log_loss IS NULL OR log_loss >= 0)
);

COMMENT ON TABLE aegis_forecast_outcomes IS 'Phase 11.16 — daily outcome backfill labels for the calibration page. forecast_id is polymorphic by forecast_kind (cve_logistic → aegis_cve_forecasts.id, etc.) — no FK constraint so we can label legacy forecasts even if their source row is later archived.';

CREATE INDEX IF NOT EXISTS idx_outcomes_kind_version ON aegis_forecast_outcomes (forecast_kind, model_version, outcome_observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_outcomes_correctness  ON aegis_forecast_outcomes (forecast_kind, was_correct) WHERE was_correct IS NOT NULL;

-- ═══════════════════════════════════════════════
-- VIEW aegis_v_top_likely_exploits — Top-50 most-likely-soon-exploited CVEs
-- ═══════════════════════════════════════════════
-- Single source for the PredictionsPanel LOGISTIC view + the
-- /feed/cyber-wire/predictions-accuracy "top successful forecasts" section.
-- Filters out CVEs already in KEV (we only forecast future weaponization).
-- Picks the most-recent forecast per (cve_id, model_version) so the panel
-- shows today's prediction, not yesterday's.

CREATE OR REPLACE VIEW aegis_v_top_likely_exploits AS
WITH latest_per_cve AS (
  SELECT DISTINCT ON (cve_id, model_version)
    cve_id, model_version, forecast_date, p_exploited_30d, p_exploited_60d, p_exploited_90d,
    ci_low, ci_high, generated_at
  FROM aegis_cve_forecasts
  ORDER BY cve_id, model_version, forecast_date DESC
)
SELECT
  l.cve_id,
  c.severity,
  c.cvss_v3_score,
  c.epss_score,
  c.epss_percentile,
  c.published_at,
  l.p_exploited_30d,
  l.p_exploited_60d,
  l.p_exploited_90d,
  l.ci_low,
  l.ci_high,
  l.model_version,
  l.forecast_date,
  l.generated_at
FROM latest_per_cve l
JOIN aegis_cves c ON c.cve_id = l.cve_id
WHERE COALESCE(c.is_kev, FALSE) = FALSE
ORDER BY l.p_exploited_30d DESC
LIMIT 50;

-- ═══════════════════════════════════════════════
-- VIEW aegis_v_forecast_accuracy_30d — Per-model rolling 30-day calibration
-- ═══════════════════════════════════════════════
-- Drives the per-model AUC / Brier / log-loss scoreboard on
-- /feed/cyber-wire/predictions-accuracy. We deliberately group by
-- (forecast_kind, model_version) — so retraining to v0.2 starts a fresh
-- calibration line rather than averaging across model versions.

CREATE OR REPLACE VIEW aegis_v_forecast_accuracy_30d AS
SELECT
  forecast_kind,
  model_version,
  COUNT(*)                                       AS sample_size,
  AVG(brier_score)                               AS mean_brier,
  AVG(log_loss)                                  AS mean_log_loss,
  AVG(CASE WHEN was_correct THEN 1.0 ELSE 0.0 END) AS hit_rate
FROM aegis_forecast_outcomes
WHERE outcome_observed_at >= NOW() - INTERVAL '30 days'
  AND was_correct IS NOT NULL
GROUP BY forecast_kind, model_version;

-- ═══════════════════════════════════════════════
-- VIEW aegis_v_situation_signal — Header FORECAST RISK + TREND chip source
-- ═══════════════════════════════════════════════
-- Single-row signal computed from the most recent forecasts + most recent
-- time-series projection. The Header chips poll /api/aegis/predictions/situation
-- every 30s; that endpoint reads this view (no aggregation needed at read-time).
--
--   next_30d_aggregate_p — mean of p_exploited_30d across top-20 unscored CVEs
--   kev_trend_7d_slope   — the latest Kalman slope for the kev_adds metric
--   kev_trend_label      — categorical: 'rising' | 'flat' | 'falling'
--
-- COALESCEs throughout so an empty forecast table doesn't crash the page —
-- chips render with sensible defaults (0 / 'flat').

CREATE OR REPLACE VIEW aegis_v_situation_signal AS
SELECT
  COALESCE(
    (SELECT AVG(p_exploited_30d)
       FROM aegis_v_top_likely_exploits
       LIMIT 20),
    0
  )::NUMERIC(5,4) AS next_30d_aggregate_p,
  COALESCE(
    (SELECT trend
       FROM aegis_timeseries_forecasts
       WHERE metric_name = 'kev_adds'
         AND horizon_days = 30
       ORDER BY forecast_date DESC
       LIMIT 1),
    'flat'
  ) AS kev_trend_label,
  COALESCE(
    (SELECT p_mid
       FROM aegis_timeseries_forecasts
       WHERE metric_name = 'kev_adds'
         AND horizon_days = 7
       ORDER BY forecast_date DESC
       LIMIT 1),
    0
  )::NUMERIC(8,2) AS kev_7d_projection,
  NOW() AS computed_at;
